// Generates lib/core/icons/hara_icons.dart from the Lucide codepoint map and
// the list of icon names in tool/icons.txt.
//
// Usage (from the haraplay/ directory): dart run tool/gen_icons.dart
import 'dart:convert';
import 'dart:io';

const _codepointsPath = 'tool/lucide_codepoints.json';
const _iconListPath = 'tool/icons.txt';
const _outputPath = 'lib/core/icons/hara_icons.dart';

void main() {
  final codepoints = (jsonDecode(
    File(_codepointsPath).readAsStringSync(),
  ) as Map<String, dynamic>).cast<String, int>();

  final names =
      File(_iconListPath)
          .readAsLinesSync()
          .map((line) => line.trim())
          .where((line) => line.isNotEmpty && !line.startsWith('#'))
          .toSet()
          .toList()
        ..sort();

  final missing = names.where((name) => !codepoints.containsKey(name));
  if (missing.isNotEmpty) {
    stderr.writeln('Unknown Lucide icons: ${missing.join(', ')}');
    exitCode = 1;
    return;
  }

  final buffer = StringBuffer()
    ..writeln('// GENERATED by tool/gen_icons.dart — do not edit by hand.')
    ..writeln('// Icons: Lucide (https://lucide.dev), ISC License.')
    ..writeln('// See assets/icons/lucide/LICENSE.')
    ..writeln()
    ..writeln("import 'package:flutter/widgets.dart';")
    ..writeln()
    ..writeln('/// Lucide icons bundled with HaraPlay.')
    ..writeln('abstract final class HaraIcons {')
    ..writeln("  static const _family = 'Lucide';")
    ..writeln();

  for (final name in names) {
    final hex = codepoints[name]!.toRadixString(16);
    buffer.writeln(
      '  static const IconData ${_camelCase(name)} = '
      'IconData(0x$hex, fontFamily: _family);',
    );
  }
  buffer
    ..writeln()
    ..writeln(
      '  /// Every bundled icon by its Lucide name (used by the design gallery).',
    )
    ..writeln('  static const Map<String, IconData> values = {');
  for (final name in names) {
    buffer.writeln("    '$name': ${_camelCase(name)},");
  }
  buffer
    ..writeln('  };')
    ..writeln('}');

  File(_outputPath)
    ..createSync(recursive: true)
    ..writeAsStringSync(buffer.toString());
  stdout.writeln('Wrote ${names.length} icons to $_outputPath');
}

String _camelCase(String kebab) {
  final parts = kebab.split('-');
  final head = parts.first;
  final tail = parts.skip(1).map((p) => p[0].toUpperCase() + p.substring(1));
  final name = [head, ...tail].join();
  // Dart identifiers cannot start with a digit (none do today, but be safe).
  return RegExp(r'^\d').hasMatch(name) ? 'i$name' : name;
}
